const ATTRS = { "stroke-width": 1.75, "aria-hidden": "true", focusable: "false" };

// Lucide leaves its placeholder attribute on the generated <svg>, which would make every
// later pass re-render it; move it to a marker attribute so a pass only touches new icons.
function markRendered(root) {
  for (const svg of root.querySelectorAll("svg[data-lucide], svg[data-icon]")) {
    svg.setAttribute("data-icon-name", svg.getAttribute("data-lucide") ?? svg.getAttribute("data-icon"));
    svg.removeAttribute("data-lucide");
    svg.removeAttribute("data-icon");
  }
  for (const template of root.querySelectorAll("template")) markRendered(template.content);
}

const toPascal = (name) => name.replace(/(^|-)([a-z0-9])/g, (_, __, letter) => letter.toUpperCase());

// An unregistered name would make Lucide log a console warning and leave an empty box;
// fall back to a visible, honest placeholder icon instead.
function guardUnknown(root) {
  for (const placeholder of root.querySelectorAll("[data-lucide], [data-icon]")) {
    if (placeholder instanceof SVGElement) continue;
    const attribute = placeholder.hasAttribute("data-lucide") ? "data-lucide" : "data-icon";
    if (!(toPascal(placeholder.getAttribute(attribute) ?? "") in icons)) placeholder.setAttribute(attribute, "circle-help");
  }
  for (const template of root.querySelectorAll("template")) guardUnknown(template.content);
}

// Replaces every placeholder under `root` (default: the whole document), including inside
// <template> elements so cloned rows already carry their SVG.
export function renderIcons(root = document) {
  if (!root || typeof root.querySelectorAll !== "function") return;
  guardUnknown(root);
  createIcons({ icons, attrs: ATTRS, root, inTemplates: true });
  createIcons({ icons, attrs: ATTRS, root, nameAttr: "data-icon", inTemplates: true });
  markRendered(root);
}

// Placeholder element for JS-built UI; call renderIcons(parent) after inserting it.
export function iconPlaceholder(name) {
  const placeholder = document.createElement("i");
  placeholder.setAttribute("data-lucide", name);
  placeholder.setAttribute("aria-hidden", "true");
  return placeholder;
}
